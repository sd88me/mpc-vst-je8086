# ---------------------------------------------------------------- CONTROL / VELOCITY assign (40 each, 10 x 4 small knobs)
def assign(name, prefix, title):
    keys = [k for k in PARAMS if k.startswith(prefix)]
    sub = [keys[i:i + 16] for i in range(0, len(keys), 16)]
    p = Page(name, sub[0], *[("%s %d" % (name, n + 2), s) for n, s in enumerate(sub[1:])])
    p.panel(8, 8, 1264, 612, title)
    for i, k in enumerate(keys):
        c, r = i % 10, i // 10
        lab = PARAMS[k]["name"].replace("C.", "").replace("V.", "").replace("CTRL ", "").replace("VEL ", "")
        lab = re.sub(r"^(CTL|VEL) ", "", lab)
        p.ctl(72 + c * 126, 112 + r * 136, k, lab[:13])
    p.done()


assign("CONTROL", "ctl_", "CONTROL (MORPH) ASSIGN")
