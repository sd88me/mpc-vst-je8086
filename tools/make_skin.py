"""The MPC layout in the look of gearmulator's JE-8086 skin "jeTrancy" (theusualsuspects): every page is drawn here (PIL) at the MPC's
1280 x 628 on the skin's blue chassis, with its orange wordmark, black section panels with orange titles (the skin's Vipnagorgialla), white
labels (Metropolis) and its knob filmstrip, laid out for the MPC rather than cropped from the plugin's 2420 x 870 panel. The panels follow the
JP-8000's own sections (LFO 1, OSC 1, OSC 2, Filter, Amp, Modulation, Pitch/Filter/Amp Envelope, Control, Effects).
    make_skin.py      writes vst/layout.conf and vst/images/page_*.png (tools/make_assets.py makes the parts it draws from)"""
