_f = {}
def F(size, face="Metropolis-SemiBold.ttf"):
    if (size, face) not in _f:
        _f[(size, face)] = ImageFont.truetype(os.path.join(FONT, face), size)
    return _f[(size, face)]
TITLE = "Vipnagorgialla Rg.ttf"

